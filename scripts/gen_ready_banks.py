ROOT = Path(__file__).resolve().parents[1]


def save_bank(method_id: str, items: list[dict]) -> None:
    p = ROOT / "questions" / method_id
    p.mkdir(parents=True, exist_ok=True)
    (p / "bank.json").write_text(json.dumps(items, ensure_ascii=False, indent=2), encoding="utf-8")
    print("bank", method_id, len(items))


